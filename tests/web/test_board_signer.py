def _cosign_headers(priv, method, path, body, cosigner, ts):
    p, _, q = path.partition("?")
    msg = bs.canonical_message(method, p, ts, body, q)
    return {"X-Board-Cosigner": cosigner, "X-Board-Cosignature": bs.sign_with_ssh_keygen(priv, msg)}


def test_policy_cosign_requires_admin_cosignature(keypair, other_keypair):
    priv, pub = keypair
    opriv, opub = other_keypair
    db.board_signer_upsert("alice", pub, "alice@laptop", role="member", kind="human")
    db.board_signer_upsert("mallory", opub, "mallory@laptop", role="member", kind="human")
    ts = int(time.time())
    sig_hdrs = _signed_headers(priv, "POST", "/api/v1/board", BODY, ts=ts)
    with patch.object(web_main.db, "board_token_valid", return_value=False):
        with pytest.raises(HTTPException):                                   # signature alone
            _auth(_req(body=BODY, **sig_hdrs), policy="cosign")
        with pytest.raises(HTTPException) as e:                              # member cosigner
            _auth(_req(body=BODY, **sig_hdrs, **_cosign_headers(opriv, "POST", "/api/v1/board", BODY, "mallory", ts)), policy="cosign")
        assert "not an admin" in e.value.detail
        db.board_signer_set_role("mallory", role="admin")
        assert _auth(_req(body=BODY, **sig_hdrs, **_cosign_headers(opriv, "POST", "/api/v1/board", BODY, "mallory", ts)), policy="cosign") == "alice"
        with pytest.raises(HTTPException) as e:                              # self-cosign
            _auth(_req(body=BODY, **sig_hdrs, **_cosign_headers(priv, "POST", "/api/v1/board", BODY, "alice", ts)), policy="cosign")
        assert "differ" in e.value.detail
        db.board_signer_set_active("mallory", False, "inert")                # inert admin cannot cosign
        with pytest.raises(HTTPException):
            _auth(_req(body=BODY, **sig_hdrs, **_cosign_headers(opriv, "POST", "/api/v1/board", BODY, "mallory", ts)), policy="cosign")


def test_deactivate_is_immediate_no_restart(keypair):
    """board_signers.active is re-read on every request: deactivate -> the very
    next request 401s with no restart, and activate restores it."""
    priv, pub = keypair
    db.board_signer_upsert("alice", pub, "alice@laptop")
    hdr = lambda: _signed_headers(priv, "POST", "/api/v1/board", BODY)  # noqa: E731
    with patch.object(web_main.db, "board_token_valid", return_value=False):
        assert _auth(_req(body=BODY, **hdr())) == "alice"
        db.board_signer_set_active("alice", False, "kill")
        with pytest.raises(HTTPException) as e:
            _auth(_req(body=BODY, **hdr()))
        assert e.value.status_code == 401
        db.board_signer_set_active("alice", True)
        assert _auth(_req(body=BODY, **hdr())) == "alice"


