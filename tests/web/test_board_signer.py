def test_query_string_is_signed(keypair):
    priv, pub = keypair
    db.board_signer_upsert("alice", pub, "alice@laptop")
    route = "GET /api/v1/vault/research"
    with patch.object(web_main.db, "board_token_valid", return_value=False):
        h = _signed_headers(priv, "GET", "/api/v1/vault/research?path=A.md", b"")
        assert _auth(_req("GET", "/api/v1/vault/research?path=A.md", b"", **h), route, db.BOARD_SCOPE_READ) == "alice"
        h2 = _signed_headers(priv, "GET", "/api/v1/vault/research?path=A.md", b"")
        with pytest.raises(HTTPException) as e:
            _auth(_req("GET", "/api/v1/vault/research?path=B.md", b"", **h2), route, db.BOARD_SCOPE_READ)
    assert e.value.status_code == 401 and "does not verify" in e.value.detail


