def test_replay_cache_expiry_and_cap():
    c = bs.ReplayCache(window=300, max_entries=3)
    assert c.check_and_add("s1", now=1000) and not c.check_and_add("s1", now=1001)
    assert c.check_and_add("s1", now=1000 + 601)          # aged out after 2x window
    for i in range(5):
        c.check_and_add(f"x{i}", now=2000)
    assert len(c._seen) == 3
