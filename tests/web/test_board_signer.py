def _req(method="POST", path="/api/v1/board", body: bytes = b"", **headers):
    """Stand-in for starlette's Request with the attributes _board_auth reads."""
    async def _body():
        return body
    p, _, q = path.partition("?")
    return SimpleNamespace(method=method, url=SimpleNamespace(path=p, query=q), headers=headers,
                           body=_body, client=SimpleNamespace(host="127.0.0.1"))


def _signed_headers(priv, method, path, body: bytes, signer="alice", ts=None):
    ts = int(time.time()) if ts is None else ts
    p, _, q = path.partition("?")
    msg = bs.canonical_message(method, p, ts, body, q)
    return {"X-Board-Signer": signer, "X-Board-Timestamp": str(ts),
            "X-Board-Signature": bs.sign_with_ssh_keygen(priv, msg)}


BODY = json.dumps({"from": "whoever", "to": "dispatch", "thread": "coord",
                   "subject": "s", "body": "b"}).encode()


# -- pure verification ---------------------------------------------------------

def test_sshsig_roundtrip_and_tamper(keypair):
    priv, pub = keypair
    msg = bs.canonical_message("POST", "/api/v1/board", 1700000000, b"{}")
    sig = bs.sign_with_ssh_keygen(priv, msg)
    assert bs.verify(pub, sig, msg) is True
    assert bs.verify(pub, sig, msg + b"x") is False


def test_wrong_key_rejected(keypair, other_keypair):
    _, pub = keypair
    opriv, _ = other_keypair
    msg = bs.canonical_message("POST", "/api/v1/board", 1700000000, b"{}")
    assert bs.verify(pub, bs.sign_with_ssh_keygen(opriv, msg), msg) is False


def test_timestamp_window():
    now = 1700000000
    assert bs.check_timestamp(str(now - 299), now) == now - 299
    with pytest.raises(bs.BoardSignError):
        bs.check_timestamp(str(now - 301), now)
    with pytest.raises(bs.BoardSignError):
        bs.check_timestamp("soon", now)


