def _minted(ttl_s, revoked=None):
    now = time.time()
    return {"created_at": now - 60, "expires_at": now - 60 + ttl_s, "scope": "board-write",
            "label": "alice", "revoked_at": revoked, "ttl_s": ttl_s}


def test_policy_high_requires_signature_and_time_based_token(keypair):
    """'both' (old name) == 'high': a valid signature AND a MINTED token whose
    lifetime is <= HIGH_TOKEN_MAX_TTL. The master key never qualifies."""
    priv, pub = keypair
    db.board_signer_upsert("alice", pub, "alice@laptop")
    sig_hdrs = _signed_headers(priv, "POST", "/api/v1/board", BODY)
    with patch.object(web_main.db, "board_token_valid", return_value=False), \
            patch.object(web_main.db, "board_token_info", return_value=None):
        with pytest.raises(HTTPException):
            _auth(_req(body=BODY, **sig_hdrs), policy="high")           # signature only
    with patch.object(web_main.db, "board_token_valid", return_value=True), \
            patch.object(web_main.db, "board_token_info", return_value=_minted(3600)):
        with pytest.raises(HTTPException):
            _auth(_req(body=BODY, **{"X-Board-Key": "minted"}), policy="high")   # token only
        assert _auth(_req(body=BODY, **{"X-Board-Key": "minted", **sig_hdrs}), policy="high") == "alice"
        assert _auth(_req(body=BODY, **{"X-Board-Key": "minted", **sig_hdrs}), policy="both") == "alice"   # alias


def test_policy_high_master_key_alone_never_qualifies(keypair):
    priv, pub = keypair
    db.board_signer_upsert("alice", pub, "alice@laptop")
    sig_hdrs = _signed_headers(priv, "POST", "/api/v1/board", BODY)
    # master key: board_token_valid False (not minted), board_token_info None
    with patch.object(web_main, "_BOARD_KEY", "MASTER"), patch.object(web_main.db, "board_token_valid", return_value=False), \
            patch.object(web_main.db, "board_token_info", return_value=None):
        assert _auth(_req(body=BODY, **{"X-Board-Key": "MASTER"}), policy="normal") is None   # normal: fine
        with pytest.raises(HTTPException) as e:
            _auth(_req(body=BODY, **{"X-Board-Key": "MASTER", **sig_hdrs}), policy="high")
    assert "does not qualify" in e.value.detail


def test_policy_high_rejects_long_lived_or_revoked_token(keypair):
    priv, pub = keypair
