def _auth(req, route="POST /api/v1/board", scope=db.BOARD_SCOPE_WRITE, policy=None, fresh=True):
    # policy tests re-present one signed request on purpose; ed25519 is
    # deterministic, so they start from an empty replay cache (U6). The
    # single-use test passes fresh=False.
    if fresh:
        web_main._BOARD_REPLAY._seen.clear()
    with patch.dict(web_main.BOARD_AUTH_POLICY, {route: policy} if policy else {}):
        return asyncio.run(web_main._board_auth(req, route, scope))


