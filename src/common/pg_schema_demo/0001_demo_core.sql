-- 0001_demo_core.sql -- the DEMO instance's whole schema (2026-10-16,
-- demo/production database split, relay 1). See pg_schema_demo/__init__.py.
--
-- Applied by scripts/pg_migrate.py --instance demo as demo_owner (the
-- instance's bootstrap owner, POSTGRES_USER in the pgsql-demo quadlet).
-- Idempotent: CREATE ... IF NOT EXISTS throughout; the role block checks
-- pg_roles first. Nothing here names a password: the `demo` role is created
-- LOGIN with NO password, so under config/pg_hba-demo.conf's scram rules it
-- cannot authenticate until the operator sets one by hand
-- (ALTER ROLE demo PASSWORD ..., typed, relay 2 hand step).

-- Bootstrap: scripts/pg_migrate.py records every applied file here (it
-- checks to_regclass('<schema>.schema_migrations') before reading it, so this
-- file must create the table before anything else).
CREATE TABLE IF NOT EXISTS schema_migrations (
    filename     TEXT PRIMARY KEY,
    applied_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    checksum     TEXT NOT NULL
);

-- Scrubbed, promoted endpoint payloads. The sovereign shape
-- scripts/scrub-demo-source.py has written since 2026-08-14 (then into a
-- SQLite file), carried over column for column: captured_at TEXT ISO-8601
-- (cast at query time, never a native timestamp -- the convention every
-- other TEXT-timestamp column in this platform follows), payload zlib bytes,
-- compressed/synthetic BOOLEAN (INTEGER 0/1 in the SQLite file; every reader
-- treats them as truthy). UNIQUE(endpoint, captured_at, synthetic) makes a
-- re-run backfill idempotent (INSERT ... ON CONFLICT DO NOTHING).
CREATE TABLE IF NOT EXISTS snapshots (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint     TEXT    NOT NULL,
    captured_at  TEXT    NOT NULL,
    payload      BYTEA   NOT NULL,
    payload_hash TEXT,
    compressed   BOOLEAN NOT NULL DEFAULT TRUE,
    synthetic    BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (endpoint, captured_at, synthetic)
);
CREATE INDEX IF NOT EXISTS idx_snapshots_ep_time ON snapshots (endpoint, captured_at);

-- Scrubbed briefs (brief_type ops / weekly / ep-advance under the strict
-- scrub). Same shape as production's brief_archive (pg_schema/0011) so
-- src/demo/demo_api.py's queries are unchanged.
CREATE TABLE IF NOT EXISTS brief_archive (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_at TEXT NOT NULL,
    brief_type   TEXT NOT NULL DEFAULT 'ops',
    content      TEXT NOT NULL,
    source       TEXT NOT NULL DEFAULT 'skill',
    UNIQUE (generated_at, brief_type)
);
CREATE INDEX IF NOT EXISTS idx_brief_archive_ts ON brief_archive (generated_at DESC);

-- window_end / promoted_at -- written only by the scrub; demo_api derives its
-- replay anchor from window_end and never from wall-clock time.
CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- Password-gated access profiles for the public demo (src/demo/profiles.py).
-- Column for column the production demo_profiles table (pg_schema/0057);
-- the demo-api process writes here as `demo` (create / revoke), which is why
-- `demo` gets INSERT/UPDATE below and on nothing else but chat_messages.
CREATE TABLE IF NOT EXISTS demo_profiles (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label         TEXT    NOT NULL,
    password_hash TEXT    NOT NULL,
    salt          TEXT    NOT NULL,
    window_days   INTEGER NOT NULL,
    speed         DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    auto_scale    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TEXT    NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE
);

-- runner-demo's dispatch-chat history (src/runner/main.py _chat_*), the
-- shape of pg_schema/0056 so the runner code runs unchanged under
-- DISPATCH_ROLE=demo. Public visitors write here; nothing else reads it.
CREATE TABLE IF NOT EXISTS chat_messages (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role    TEXT    NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT    NOT NULL,
    ts      DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_chat_ts ON chat_messages (ts);

-- Hash-chained ledger of scrub runs, the construction of production's
-- reference_import_ledger (pg_schema/0074): entry_hash = sha256(prev_hash |
-- canonical body); UNIQUE(prev_hash) and UNIQUE(entry_hash) make a second
-- concurrent writer FAIL rather than fork the chain. Counts and class
-- names only -- never a payload, identifier or drop reason value.
CREATE TABLE IF NOT EXISTS scrub_ledger (
    seq                INTEGER PRIMARY KEY,
    run_at             TEXT    NOT NULL,
    mode               TEXT    NOT NULL,
    window_start       TEXT,
    window_end         TEXT,
    snapshots_promoted INTEGER NOT NULL,
    snapshots_dropped  INTEGER NOT NULL,
    briefs_promoted    INTEGER NOT NULL,
    briefs_dropped     INTEGER NOT NULL,
    dropped_by_class   TEXT    NOT NULL,
    synthetic_filled   INTEGER NOT NULL DEFAULT 0,
    pruned             INTEGER NOT NULL DEFAULT 0,
    ladd_count         INTEGER NOT NULL,
    prev_hash          TEXT    NOT NULL UNIQUE,
    entry_hash         TEXT    NOT NULL UNIQUE
);

-- The application role. LOGIN but no password until the operator sets one;
-- NOINHERIT / no CREATE anything. Grants are the minimum the two demo
-- containers need: read the playback tables, maintain demo_profiles,
-- read/append/clear chat_messages. No DELETE on snapshots/brief_archive/meta
-- /scrub_ledger (the scrub, as demo_owner, is their only writer).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'demo') THEN
        CREATE ROLE demo LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION;
    END IF;
END
$$;
GRANT USAGE ON SCHEMA public TO demo;
GRANT SELECT ON snapshots, brief_archive, meta, scrub_ledger, schema_migrations TO demo;
GRANT SELECT, INSERT, UPDATE ON demo_profiles TO demo;
GRANT SELECT, INSERT, DELETE ON chat_messages TO demo;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO demo;
