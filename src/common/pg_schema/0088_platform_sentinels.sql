-- 0088_platform_sentinels.sql -- platform-side sentinels (2026-11-18, operator): they run as
-- timers on the box so they keep working when the agents are offline (the 11-04..11-17
-- agent-side lapse). Code: common/platform_sentinels.py and the four modules beside it;
-- SQLite twins: db.py's flight_events DDL and platform_sentinels.ensure().
-- Idempotent.
--
-- flight_events.first_seen_*: set on INSERT only (db.upsert_flight_event), never updated.
-- Rows that existed before this migration keep NULL (unknown) -- the coverage report and
-- the per-ARTCC sentinel count only rows that have it.
ALTER TABLE flight_events ADD COLUMN IF NOT EXISTS first_seen_at DOUBLE PRECISION;
ALTER TABLE flight_events ADD COLUMN IF NOT EXISTS first_seen_centre TEXT;
ALTER TABLE flight_events ADD COLUMN IF NOT EXISTS first_seen_source TEXT;
CREATE INDEX IF NOT EXISTS idx_flight_events_first_seen_at ON flight_events(first_seen_at);

-- the ground-stop tripwire reads GS/GDP rows by type and fetched_at every 5 min (a read-only scan of
-- this table by fetched_at alone hit the RO role's statement timeout on 2026-11-18)
CREATE INDEX IF NOT EXISTS idx_nas_programs_type_fetched ON nas_programs(type, fetched_at);

-- the agent-lapse sentinel reads the last agent.tool.call / board.signed.request rows every 30 min; an
-- index only (no row of the hash-chained audit_log is touched)
CREATE INDEX IF NOT EXISTS idx_audit_log_action_time ON audit_log(action, event_time);

-- agent_lapse_state: the agent-lapse sentinel's view of each agent account (written by the
-- host timer, read by the operator console). detail is JSON text.
CREATE TABLE IF NOT EXISTS agent_lapse_state (
    account        TEXT PRIMARY KEY,
    last_activity  DOUBLE PRECISION,
    stage          TEXT NOT NULL,
    episode        TEXT,
    stage_sent     TEXT,
    detail         TEXT,
    updated_at     DOUBLE PRECISION NOT NULL
);

-- agent_lapse_dismissals: the operator's dismissals (SSH CLI or console). A dismissal holds
-- until `until_at`, or until the account shows activity after `dismissed_at`.
CREATE TABLE IF NOT EXISTS agent_lapse_dismissals (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account        TEXT NOT NULL,
    dismissed_at   DOUBLE PRECISION NOT NULL,
    until_at       DOUBLE PRECISION NOT NULL,
    by_who         TEXT NOT NULL,
    via            TEXT NOT NULL,
    reason         TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_agent_lapse_dismissals_account ON agent_lapse_dismissals(account, until_at);
