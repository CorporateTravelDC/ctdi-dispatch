-- 0085_withheld.sql -- withheld categories, passes and the master token
-- (2026-11-02, operator directive). src/common/withheld.py ensure() is the
-- SQLite twin (test suite only).
-- Tables: withheld_settings, withheld_identifiers, withheld_pairings,
--         withheld_masters, withheld_audit
--
-- withheld_settings: the kill switch ('frozen' = every category, 'frozen:<cat>'
-- = one). Thawing needs the operator's SSH-signed withheld-thaw approval.
-- withheld_identifiers: the operator-kept lists for categories that have no
-- external list (rail, vessel). Aircraft use faa_ladd_aircraft.
-- withheld_pairings: one row per signed pass / master request; code_hash is the
-- sha256 of the one-time pairing code (the code itself is never stored); a
-- master row also records the verified operator GPG fingerprint.
-- withheld_masters: live master tokens. Every kill DELETES these rows and the
-- matching auth_tokens rows; a thaw never restores them.
-- withheld_audit: keyed digests only (HMAC-SHA-512 with WITHHELD_AUDIT_KEY),
-- never an identifier.
--
-- Idempotent: CREATE TABLE/INDEX IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS withheld_settings (
    key        TEXT PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL,
    updated_by TEXT
);

CREATE TABLE IF NOT EXISTS withheld_identifiers (
    category TEXT NOT NULL,
    kind     TEXT NOT NULL,
    value    TEXT NOT NULL,
    added_at DOUBLE PRECISION NOT NULL,
    added_by TEXT,
    PRIMARY KEY (category, kind, value)
);

CREATE TABLE IF NOT EXISTS withheld_pairings (
    code_hash       TEXT PRIMARY KEY,
    kind            TEXT NOT NULL CHECK (kind IN ('pass', 'master')),
    categories      TEXT NOT NULL,
    approval_id     TEXT NOT NULL,
    device_label    TEXT NOT NULL,
    hours           DOUBLE PRECISION NOT NULL,
    issued_by       TEXT NOT NULL,
    created_at      DOUBLE PRECISION NOT NULL,
    expires_at      DOUBLE PRECISION NOT NULL,
    used_at         DOUBLE PRECISION,
    gpg_fpr         TEXT,
    gpg_verified_at DOUBLE PRECISION,
    token_hash      TEXT
);
CREATE INDEX IF NOT EXISTS withheld_pairings_approval_idx ON withheld_pairings (approval_id);

CREATE TABLE IF NOT EXISTS withheld_masters (
    token_hash   TEXT PRIMARY KEY,
    user_label   TEXT NOT NULL,
    device_label TEXT NOT NULL,
    approval_id  TEXT NOT NULL,
    gpg_fpr      TEXT NOT NULL,
    created_at   DOUBLE PRECISION NOT NULL,
    expires_at   DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS withheld_audit (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts           DOUBLE PRECISION NOT NULL,
    minute       TEXT NOT NULL,
    kind         TEXT NOT NULL CHECK (kind IN ('reveal', 'lockdown')),
    category     TEXT NOT NULL,
    user_label   TEXT,
    device_label TEXT,
    path         TEXT,
    digest       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS withheld_audit_ts_idx ON withheld_audit (ts);
CREATE INDEX IF NOT EXISTS withheld_audit_digest_idx ON withheld_audit (digest);
