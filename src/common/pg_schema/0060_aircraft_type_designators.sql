-- Migration 0060: ICAO aircraft type designator reference table
-- Static reference data (designator -> aircraft type name), sourced from
-- airplanes.live's live 'Aircraft Types Flying Now' page (operator-supplied
-- screenshots, 2026-09-20). The designator->name mapping is durable (ICAO
-- type designators are a fixed registry); the live aircraft COUNTS on that
-- page are NOT captured here (refresh every 30s, not durable data).
--
-- Built to fix a real false-positive bug in geometric reasoning Phase 0's
-- flight extractor (assign_geometry() in second_brain/semantic/compile.py):
-- text like "Type: Boeing 737 MAX 8" was extracted as flight identifier
-- 'MAX8' because 'MAX' is a real (if obscure) value in flight_events.airline.
-- The primary fix is requiring the full (airline, flight_num) pair to exist
-- in flight_events, not just the airline prefix -- this table is kept as
-- genuinely useful standalone reference data (operator's explicit request),
-- not as a live per-extraction join.
--
-- Idempotent: CREATE TABLE/INSERT ON CONFLICT DO NOTHING.

