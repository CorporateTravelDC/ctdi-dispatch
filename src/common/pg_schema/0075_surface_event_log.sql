-- 0075_surface_event_log.sql -- append-only ASDE-X surface event log (2026-10-14).
--
-- surface_movement_events is a slot table keyed (airport, track_id): each new
-- event for a track overwrites the last, so a flight's ramp exit (spotout) is
-- gone once its takeoff (off) arrives. The airline time-fidelity research
-- (docs/research/AIRLINE_TIME_FIDELITY_CHECKPOINT_2026-10-13.md, next steps 1-2)
-- needs every event with its track and route. DCA/IAD/BWI only
-- (db.SURFACE_EVENT_LOG_AIRPORTS), OOOI-relevant events only, one row per
-- distinct (airport, track, event, event time); 120-day retention
-- (retention_prune).

CREATE TABLE IF NOT EXISTS surface_event_log (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport              TEXT NOT NULL,
    track_id             TEXT NOT NULL,
    callsign             TEXT,
    event                TEXT NOT NULL,
    status               TEXT,
    runway               TEXT,
    event_time           TEXT NOT NULL,
    departure_airport    TEXT,
    destination_airport  TEXT,
    logged_at            TEXT NOT NULL,
    UNIQUE (airport, track_id, event, event_time)
);
CREATE INDEX IF NOT EXISTS idx_surface_event_log_callsign
    ON surface_event_log(callsign, airport, event_time);
CREATE INDEX IF NOT EXISTS idx_surface_event_log_logged
    ON surface_event_log(logged_at);
