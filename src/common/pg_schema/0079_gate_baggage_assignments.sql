-- 0079_gate_baggage_assignments.sql -- gate / terminal / baggage assignment model (2026-10-18, gate batch).
--
-- Operator decisions 2026-10-18 (gate precedence): SWIM (TDES parkingGate; TFDM
-- stand later) > ACARS (airframes.io = Jumpseat = local, one tier) > AeroAPI
-- (fallback only, budgeted) > MWAA FIDS (DC only, gate/terminal/baggage only).
-- FIDS never supplies a time, a status or a tail: no column here can hold one.
--
--   gate_baggage_observations        append-only evidence, one row per distinct
--                                    source event (content_key). last_seen_at is
--                                    the only column a duplicate may move, and only
--                                    for a display source (FIDS) re-showing a value.
--   gate_baggage_assignments         resolved current state, one row per
--                                    (leg, side, field) -- common.gate_assignments.resolve.
--   gate_baggage_assignment_history  every revision of a resolved state.
--   aeroapi_gate_calls               ledger of every AeroAPI fallback call; UNIQUE
--                                    (leg_key, purpose) holds the 2-calls-per-leg cap.
--
-- Leg key = common.flight_instance.FlightInstanceKey (operating carrier, number,
-- origin, destination, UTC date of the scheduled departure); NULL parts mean
-- "unknown", never a wildcard. LADD-listed legs are dropped before storage
-- (fail closed). Production only: not in the demo instance or the scrub allowlist.
-- 120-day retention (poller/skills/retention_prune.py). SQLite twin:
-- common.gate_assignments._SQLITE_DDL (db.init_db_v48).

CREATE TABLE IF NOT EXISTS gate_baggage_observations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leg_key         TEXT NOT NULL,
    carrier         TEXT NOT NULL,
    flight_num      TEXT NOT NULL,
    origin          TEXT,
    destination     TEXT,
    sched_date      TEXT,
    airport         TEXT,
    side            TEXT NOT NULL CHECK (side IN ('departure', 'arrival')),
    field           TEXT NOT NULL CHECK (field IN ('gate', 'terminal', 'baggage', 'stand')),
    value_raw       TEXT,
    value_norm      TEXT,
    is_placeholder  BOOLEAN NOT NULL DEFAULT FALSE,
    flags           TEXT,
    source          TEXT NOT NULL CHECK (source IN ('swim_tdes', 'swim_tfdm', 'acars_airframes',
                                                     'acars_jumpseat', 'acars_local', 'aeroapi',
                                                     'mwaa_fids')),
    source_tier     SMALLINT NOT NULL,
    raw_table       TEXT,
    raw_ref         TEXT,
    parser_version  TEXT NOT NULL,
    observed_at     TEXT NOT NULL,
    effective_at    TEXT,
    ingested_at     TEXT NOT NULL,
    last_seen_at    TEXT NOT NULL,
    leg_match       TEXT NOT NULL CHECK (leg_match IN ('exact', 'route_date', 'route_watch', 'route_only')),
    evidence_type   TEXT NOT NULL CHECK (evidence_type IN ('clearance', 'assignment_change',
                                                            'assignment_msg', 'api', 'display')),
    confidence      REAL NOT NULL,
    verification    TEXT NOT NULL DEFAULT 'none',
    status          TEXT NOT NULL DEFAULT 'accepted' CHECK (status IN ('accepted', 'placeholder')),
    content_key     TEXT NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS idx_gbo_leg ON gate_baggage_observations (leg_key, side, field);
CREATE INDEX IF NOT EXISTS idx_gbo_flight ON gate_baggage_observations (carrier, flight_num, sched_date);
CREATE INDEX IF NOT EXISTS idx_gbo_ingested ON gate_baggage_observations (ingested_at);

CREATE TABLE IF NOT EXISTS gate_baggage_assignments (
    leg_key           TEXT NOT NULL,
    side              TEXT NOT NULL,
    field             TEXT NOT NULL,
    carrier           TEXT NOT NULL,
    flight_num        TEXT NOT NULL,
    origin            TEXT,
    destination       TEXT,
    sched_date        TEXT,
    airport           TEXT,
    value_norm        TEXT,
    status            TEXT NOT NULL CHECK (status IN ('observed', 'provisional', 'superseded',
                                                       'conflicting', 'unknown')),
    winning_obs_id    BIGINT,
    conflicting_values TEXT,
    source            TEXT,
    resolver_version  TEXT NOT NULL,
    push_key          TEXT NOT NULL,
    revision          INTEGER NOT NULL DEFAULT 1,
    resolved_at       TEXT NOT NULL,
    PRIMARY KEY (leg_key, side, field)
);
CREATE INDEX IF NOT EXISTS idx_gba_flight ON gate_baggage_assignments (carrier, flight_num, sched_date);
CREATE INDEX IF NOT EXISTS idx_gba_resolved ON gate_baggage_assignments (resolved_at);

CREATE TABLE IF NOT EXISTS gate_baggage_assignment_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leg_key         TEXT NOT NULL,
    side            TEXT NOT NULL,
    field           TEXT NOT NULL,
    revision        INTEGER NOT NULL,
    prev_value      TEXT,
    new_value       TEXT,
    prev_status     TEXT,
    new_status      TEXT,
    winning_obs_id  BIGINT,
    source          TEXT,
    reason          TEXT NOT NULL,
    resolved_at     TEXT NOT NULL,
    UNIQUE (leg_key, side, field, revision)
);
CREATE INDEX IF NOT EXISTS idx_gbah_resolved ON gate_baggage_assignment_history (resolved_at);

CREATE TABLE IF NOT EXISTS aeroapi_gate_calls (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    called_at    TEXT NOT NULL,
    call_day     TEXT NOT NULL,
    leg_key      TEXT NOT NULL,
    purpose      TEXT NOT NULL CHECK (purpose IN ('pre_eta', 'post_on')),
    http_status  INTEGER,
    outcome      TEXT,
    UNIQUE (leg_key, purpose)
);
CREATE INDEX IF NOT EXISTS idx_aeroapi_gate_calls_day ON aeroapi_gate_calls (call_day);
