-- 0084_semantic_vessel_drone_geometry.sql -- maritime and drone geometry
-- (2026-10-22, operator approval under the feature freeze; closes
-- docs/GEOMETRIC_REASONING_DESIGN_2026-09-17.md decision #6, "deferred but
-- not absent": schema now, seeded from a public sample where one exists).
-- src/common/db.py init_db_v53 is the SQLite twin.
-- Tables: drone_events, ais_sample_positions
--
-- Must be applied BEFORE a poller image whose compile.py resolves vessel and
-- drone positions: the compile runs in one transaction and reads both tables.
--
-- drone_events: one Remote ID / UTM position per row, keyed by the broadcast
-- UAS ID (CTA-2063-A serial or session ID, upper-cased, dashes removed, as
-- utm_watcher.normalize_uas_id() does). Nothing writes it yet: no receiver is
-- installed and utm_watcher writes no table. Deliberately NO operator id and
-- NO operator position columns: those identify a person, and no privacy rule
-- for them exists yet (the LADD gate covers aircraft only).
--
-- ais_sample_positions: the NOAA Marine Cadastre AIS sample, loaded by
-- scripts/seed-ais-sample.py from a daily file the operator downloads. Kept
-- OUT of vessel_events on purpose: vessel_events is the live table that
-- analyze_vessel_patterns(), the transport digest and the docs read as "what
-- moved near DC", and sample rows there would read as live traffic. `dataset`
-- names the source file, so every row says where it came from.

SET LOCAL lock_timeout = '10s';

CREATE TABLE IF NOT EXISTS drone_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uas_id       TEXT NOT NULL,
    lat          DOUBLE PRECISION,
    lon          DOUBLE PRECISION,
    alt_m        DOUBLE PRECISION,
    observed_at  DOUBLE PRECISION NOT NULL,   -- epoch seconds (UTC)
    source       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_drone_events_uas ON drone_events(uas_id, observed_at);

CREATE TABLE IF NOT EXISTS ais_sample_positions (
    dataset      TEXT NOT NULL,               -- e.g. 'marinecadastre:AIS_2024_01_01'
    mmsi         TEXT NOT NULL,               -- 9 digits, zero-padded
    observed_at  DOUBLE PRECISION NOT NULL,   -- BaseDateTime as epoch seconds (UTC)
    lat          DOUBLE PRECISION NOT NULL,
    lon          DOUBLE PRECISION NOT NULL,
    sog          DOUBLE PRECISION,
    cog          DOUBLE PRECISION,
    vessel_type  TEXT,
    PRIMARY KEY (dataset, mmsi, observed_at)
);
CREATE INDEX IF NOT EXISTS idx_ais_sample_mmsi ON ais_sample_positions(mmsi, observed_at);
