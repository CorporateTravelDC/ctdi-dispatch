#!/usr/bin/env bash
# scripts/backup/ctdi-backup-direct.sh -- nightly encrypted backup straight to the off-box target, staged on
# the USB only as a short-lived offload (2026-11-19, operator; docs/BACKUP.md "Direct backup").
#
# Why: on 2026-11-19 the USB backup stick dropped off the bus (9,430 btrfs read errors) and the Borg repository
# on it became unreadable, so nothing current existed off the box. The NVMe (49 GB free) cannot hold a Borg
# repository for a 38 GB database. This path keeps no repository anywhere on the box: each object is dumped,
# compressed and encrypted as it is written to a staging folder, its ciphertext hash taken as it is written,
# re-read and checked, uploaded, checked again on the remote, and only then deleted. Nothing stays staged after
# a successful run. The USB (or the NVMe) is an offload location, not storage.
#
# Why stage at all instead of streaming the dump to the remote: pg_dump holds one database snapshot open for
# its whole run. Streamed at the 2.5 MB/s upload cap, a ~15 GB dump would hold that snapshot for 1.5-2 h,
# which blocks vacuum and bloats every busy table. Dumping to local disk finishes in minutes; the slow
# upload happens afterwards from the finished file.
#
# Objects per run (all zstd-compressed, then gpg-encrypted to an operator PUBLIC key; the box never holds the
# private key, so restore needs the operator's key off the box; Proton Drive adds its own E2E layer):
#   dispatch.pgdump.zst.gpg     dispatch Postgres, pg_dump -Fc -Z 0 | zstd (one compression pass, not two),
#                               LADD table DATA excluded (CUI never leaves the box; the ledger gets a # stamp)
#   nextcloud.pgdump.zst.gpg    Nextcloud database
#   state.tar.zst.gpg           /etc/corporatetraveldc, /var/lib/corporatetraveldc (models excluded: pinned by
#                               digest), vnstat, ntfy, Open WebUI (cache excluded), the operational config paths
#                               the Borg path archives, and the private backup ledger
#   volumes.tar.zst.gpg         named volumes: nextcloud-html (the vault and files), protonbridge-data (Proton
#                               Bridge identity; mail cache, logs, updates excluded)
# Not in the direct set (and why): the ultrafeeder graphs/history volumes (receiver statistics, regenerated by
# the feeder); the demo Postgres instance (rebuilt from production by scrub-demo-source.py --backfill); model
# files (pinned by digest, re-downloadable); caches.
#
# Staging order: the USB stage (BACKUP_DIRECT_STAGE) when its device is really there -- block-device state
# running, mounted read-write, and a write+read probe passes (findmnt alone still showed the dead stick as
# mounted on 2026-11-19) -- else the NVMe stage when stage_guard says the object fits above the reserve, else
# STREAM straight to the remote, but only for objects smaller than BACKUP_DIRECT_STREAM_MAX_GB. A dispatch dump
# that cannot be staged is SKIPPED with an alert, never streamed for hours and never allowed to fill a disk.
#
# Settings (/etc/corporatetraveldc/dispatch.env; defaults in brackets):
#   BACKUP_TARGET_DIRECT          rclone remote:path for direct runs (required; must not be BACKUP_TARGET, the
#                                 Borg mirror, or inside it)
#   BACKUP_DIRECT_GPG_RECIPIENT   40-hex fingerprint of the operator key to encrypt to (required)
#   BACKUP_DIRECT_GPG_PUBKEY      [/etc/corporatetraveldc/backup/direct-recipient.asc] that public key
#   BACKUP_DIRECT_STAGE           [/srv/ctdc-backup-usb/stage-direct]   BACKUP_DIRECT_STAGE_MOUNT [/srv/ctdc-backup-usb]
#   BACKUP_DIRECT_NVME_STAGE      [~/.local/state/ctdc-backup/stage-direct]
#   BACKUP_MIN_FREE_GB [10]  BACKUP_DIRECT_STREAM_MAX_GB [2]  BACKUP_DIRECT_STAGE_FACTOR [0.6]
#   BACKUP_DIRECT_KEEP_DAILY/WEEKLY/MONTHLY  [7 / 4 / 3]
#   BACKUP_RCLONE_CONFIG, BACKUP_RCLONE_TRANSFERS [1], BACKUP_BWLIMIT_SOFT_MB [2.5], BACKUP_BWLIMIT_HARD_MB [3],
#   BACKUP_IFACE [wld0]  -- as the Borg path
# Never uploads on a metered uplink: the heavy-work turn waits for the primary, and every upload re-checks.
#
# Usage: ctdi-backup-direct.sh [--dry-run]
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
HERE="${REPO_DIR}/scripts/backup"
ENV_FILE="${CTDC_ENV_FILE:-/etc/corporatetraveldc/dispatch.env}"
LEDGER_PY="${HERE}/backup_ledger.py"
TAP="${HERE}/stream_tap.py"
STAGE_GUARD="${HERE}/stage_guard.py"
SYSFS="${CTDC_SYSFS:-/sys}"
RATE_GUARD="${CTDC_TEST_RATE_GUARD:-${HERE}/rate_guard.py}"   # tests substitute a stub; never a dispatch.env setting
read_env() { [[ -f "$ENV_FILE" ]] && grep -m1 "^$1=" "$ENV_FILE" | cut -d= -f2- || true; }   # parsed, never sourced
setting() { local v; v="${!1:-}"; [[ -n "$v" ]] || v="$(read_env "$1")"; echo "${v:-$2}"; }

STATE="${HOME}/.local/state/ctdc-backup"
TARGET="$(setting BACKUP_TARGET_DIRECT '')"
BORG_TARGET="$(setting BACKUP_TARGET '')"
RECIPIENT="$(setting BACKUP_DIRECT_GPG_RECIPIENT '')"
PUBKEY="$(setting BACKUP_DIRECT_GPG_PUBKEY /etc/corporatetraveldc/backup/direct-recipient.asc)"
STAGE_USB="$(setting BACKUP_DIRECT_STAGE /srv/ctdc-backup-usb/stage-direct)"
STAGE_USB_MOUNT="$(setting BACKUP_DIRECT_STAGE_MOUNT /srv/ctdc-backup-usb)"
STAGE_NVME="$(setting BACKUP_DIRECT_NVME_STAGE "${STATE}/stage-direct")"
MIN_FREE=$(( $(setting BACKUP_MIN_FREE_GB 10) * 1073741824 ))
STREAM_MAX=$(( $(setting BACKUP_DIRECT_STREAM_MAX_GB 2) * 1073741824 ))
FACTOR="$(setting BACKUP_DIRECT_STAGE_FACTOR 0.6)"
KEEP_D="$(setting BACKUP_DIRECT_KEEP_DAILY 7)"; KEEP_W="$(setting BACKUP_DIRECT_KEEP_WEEKLY 4)"; KEEP_M="$(setting BACKUP_DIRECT_KEEP_MONTHLY 3)"
RCLONE_CONFIG="$(setting BACKUP_RCLONE_CONFIG "${HOME}/.config/rclone/rclone.conf")"
RCLONE_TRANSFERS="$(setting BACKUP_RCLONE_TRANSFERS 1)"
BW_SOFT="$(setting BACKUP_BWLIMIT_SOFT_MB 2.5)"; BW_HARD="$(setting BACKUP_BWLIMIT_HARD_MB 3)"; BW_IFACE="$(setting BACKUP_IFACE wld0)"
DISPATCH_PG=corporatetraveldc-pgsql
NEXTCLOUD_PG=nextcloud-db
LADD_TABLES=(faa_ladd_aircraft faa_ladd_removals)   # CUI: identifiers of LADD-listed aircraft -- never off the box
DIRECT_VOLUMES=(nextcloud-html protonbridge-data)
DRY=0
for a in "$@"; do case "$a" in --dry-run) DRY=1 ;; *) echo "usage: $0 [--dry-run]" >&2; exit 64 ;; esac; done

log() { printf '[%s] [backup-direct] %s\n' "$(date -u +%FT%TZ)" "$*"; }
ledger() { python3 "$LEDGER_PY" append "$1" --json "$2" >/dev/null; }
die() { log "ERROR: $*"; ledger note "{\"mode\": \"direct\", \"error\": \"$(echo "$*" | tr -d '"\\' | head -c 300)\"}" 2>/dev/null || true; exit 1; }

# ---- settings that must hold before anything runs -------------------------------------------------------
[[ -n "$TARGET" ]] || die "BACKUP_TARGET_DIRECT is not set"
if [[ -n "$BORG_TARGET" ]] && { [[ "$TARGET" == "$BORG_TARGET" ]] || [[ "$TARGET" == "$BORG_TARGET"/* ]] || [[ "$BORG_TARGET" == "$TARGET"/* ]]; }; then
  die "BACKUP_TARGET_DIRECT ($TARGET) overlaps BACKUP_TARGET ($BORG_TARGET); direct runs need their own folder so retention can never touch the Borg mirror"
fi
[[ "$RECIPIENT" =~ ^[0-9A-Fa-f]{40}$ ]] || die "BACKUP_DIRECT_GPG_RECIPIENT must be a 40-hex key fingerprint"
[[ -r "$PUBKEY" ]] || die "recipient public key $PUBKEY is missing or unreadable"
command -v zstd >/dev/null || die "zstd is not installed"
command -v gpg >/dev/null || die "gpg is not installed"
command -v rclone >/dev/null || die "rclone is not installed"

mkdir -p -m 0700 "$STATE"
exec 8>"${STATE}/.direct.lock"; flock -n 8 || die "another direct backup is running"

# ---- encryption: a throwaway keyring holding only the recipient's PUBLIC key ----------------------------
# --no-autostart: public-key import and encryption need no agent, and none is started (no cached secrets).
GHOME="$(mktemp -d "${STATE}/gpg.XXXX")"; chmod 700 "$GHOME"
RUN_STAGE=""
cleanup() { rm -rf "$GHOME"; [[ -n "$RUN_STAGE" && -d "$RUN_STAGE" ]] && rm -rf "$RUN_STAGE"; true; }
trap cleanup EXIT
GPG=(gpg --homedir "$GHOME" --batch --no-tty --no-autostart --quiet)
"${GPG[@]}" --import "$PUBKEY" 2>/dev/null || die "could not import $PUBKEY"
caps="$("${GPG[@]}" --with-colons --list-keys "$RECIPIENT" 2>/dev/null || true)"
[[ -n "$caps" ]] || die "$PUBKEY does not hold the key $RECIPIENT"
# a usable encryption key: a pub/sub line that is not revoked/expired (field 2) and can encrypt (field 12 has e)
awk -F: '($1=="pub"||$1=="sub") && $2!~/[rei]/ && $12~/e/ {ok=1} END {exit !ok}' <<<"$caps" \
  || die "key $RECIPIENT has no usable encryption (sub)key; add one or name a key that has it"
encrypt() { "${GPG[@]}" --trust-model always --compress-algo none --encrypt --recipient "$RECIPIENT" --output -; }

if [[ "$DRY" == 1 ]]; then
  log "dry run: would stage, encrypt to ${RECIPIENT:0:8}..., upload to ${TARGET} and prune ${KEEP_D}/${KEEP_W}/${KEEP_M}"
  exit 0
fi

source "${REPO_DIR}/scripts/lib/heavy_lock.sh"   # also brings lib/uplink.sh
psql_in() { podman exec -i "$1" sh -c "PGPASSWORD=\"\$POSTGRES_PASSWORD\" psql -At -U \"\$POSTGRES_USER\" -d \"\$POSTGRES_DB\" -c \"$2\"" </dev/null; }

# ---- sizes (for the staging decision; the stage_guard limit is what actually protects the disk) ----------
db_bytes=$(psql_in "$DISPATCH_PG" "SELECT pg_database_size(current_database())") || die "cannot read the dispatch database size"
ladd_bytes=$(psql_in "$DISPATCH_PG" "SELECT coalesce(sum(pg_total_relation_size(c.oid)),0) FROM pg_class c WHERE c.relname IN ($(printf "'%s'," "${LADD_TABLES[@]}" | sed 's/,$//'))") || ladd_bytes=0
nc_bytes=$(psql_in "$NEXTCLOUD_PG" "SELECT pg_database_size(current_database())") || die "cannot read the Nextcloud database size"
est() { python3 - "$1" "$FACTOR" <<'PY'
import sys
print(int(int(sys.argv[1]) * float(sys.argv[2])))
PY
}
EST_DISPATCH=$(est $(( db_bytes - ladd_bytes ))); EST_NC=$(est "$nc_bytes")

heavy_lock_acquire "direct backup" 7200 || die "heavy-work turn still taken after 2 h, or the metered uplink stayed the default route; backup skipped"

# ---- choose the stage ----------------------------------------------------------------------------------
dev_state_ok() {   # the block device under DIR is present and running (USB) or live (NVMe)
  local src dev disk st
  src="$(findmnt -no SOURCE --target "$1" 2>/dev/null | head -n 1)"; src="${src%%[*}"
  [[ -b "$src" || -n "${CTDC_TEST_ANY_BLOCKDEV:-}" ]] || return 1
  dev="$(basename "$src")"; disk="$(lsblk -no PKNAME "$src" 2>/dev/null | head -n 1)"; disk="${disk:-$dev}"
  st="$(cat "${SYSFS}/block/${disk}/device/state" 2>/dev/null || echo running)"
  [[ "$st" == running || "$st" == live ]]
}
mounted_rw() { findmnt -no OPTIONS --target "$1" 2>/dev/null | head -n 1 | tr ',' '\n' | grep -qx rw; }
write_probe() {    # 1 MiB written, synced, read back and compared
  local p="$1/.probe.$$" a b
  head -c 1048576 /dev/urandom > "$p" 2>/dev/null && sync -f "$p" 2>/dev/null || { rm -f "$p"; return 1; }
  a="$(python3 "$TAP" --file "$p" 2>/dev/null)"; b="$(timeout 30 cat "$p" 2>/dev/null | sha256sum | cut -d' ' -f1)"
  rm -f "$p"
  [[ -n "$b" && "$a" == *"\"sha256\": \"$b\""* ]]
}
fits() { python3 "$STAGE_GUARD" preflight "$1" "$2" "$MIN_FREE" >/dev/null 2>&1; }
need=$(( EST_DISPATCH + EST_NC ))
STAGE_MODE=stream; STAGE_DIR=""
if mountpoint -q "$STAGE_USB_MOUNT" 2>/dev/null && dev_state_ok "$STAGE_USB_MOUNT" && mounted_rw "$STAGE_USB_MOUNT" \
   && mkdir -p -m 0700 "$STAGE_USB" 2>/dev/null && write_probe "$STAGE_USB" && fits "$STAGE_USB" "$need"; then
  STAGE_MODE=usb; STAGE_DIR="$STAGE_USB"
elif mkdir -p -m 0700 "$STAGE_NVME" && fits "$STAGE_NVME" "$need"; then
  STAGE_MODE=nvme; STAGE_DIR="$STAGE_NVME"
fi
log "stage: ${STAGE_MODE}${STAGE_DIR:+ (${STAGE_DIR})}; estimated dispatch $(( EST_DISPATCH / 1048576 )) MiB, nextcloud $(( EST_NC / 1048576 )) MiB"
if [[ -n "$STAGE_DIR" ]]; then
  # objects left by an earlier, interrupted run are encrypted and unverified: discard them, never upload them
  find "$STAGE_DIR" -mindepth 1 -maxdepth 1 -type d -name '20*Z' -exec rm -rf {} + 2>/dev/null || true
fi

run="$(date -u +%Y%m%dT%H%M%SZ)"
if [[ -n "$STAGE_DIR" ]]; then RUN_STAGE="${STAGE_DIR}/${run}"; mkdir -m 0700 "$RUN_STAGE"; fi
META_DIR="$(mktemp -d "${STATE}/meta.XXXX")"; chmod 700 "$META_DIR"
trap 'cleanup; rm -rf "$META_DIR"' EXIT
PARTIAL=0; OBJECTS="[]"

add_object() {   # name, meta-json, mode
  OBJECTS="$(python3 - "$OBJECTS" "$1" "$2" "$3" <<'PY'
import json, sys
objs = json.loads(sys.argv[1]); meta = json.loads(sys.argv[3])
objs.append({"name": sys.argv[2], "bytes": meta["bytes"], "sha256": meta["sha256"], "sha1": meta["sha1"], "staged": sys.argv[4]})
print(json.dumps(objs))
PY
)"
}

remote_check() {   # name, meta-json: the remote object must have the recorded size (and sha1 when the backend gives one)
  python3 - "$2" <<PY
import json, subprocess, sys
meta = json.loads(sys.argv[1])
out = subprocess.run(["podman", "unshare", "rclone", "--config", "${RCLONE_CONFIG}", "lsjson", "--hash", "${TARGET}/${run}/$1"],
                     capture_output=True, text=True, stdin=subprocess.DEVNULL)
if out.returncode != 0:
    print("remote listing failed"); sys.exit(1)
items = json.loads(out.stdout or "[]")
if len(items) != 1 or int(items[0].get("Size", -1)) != meta["bytes"]:
    print("remote size mismatch"); sys.exit(1)
h = (items[0].get("Hashes") or {}).get("sha1")
if h and h.lower() != meta["sha1"]:
    print("remote sha1 mismatch"); sys.exit(1)
print("remote ok" + (" (size + sha1)" if h else " (size)"))
PY
}

upload_file() {    # local file -> TARGET/run/ with the rate guard; one retry on a stall
  local f="$1" attempt src grc guard_json rpid rcdir soft_k
  for attempt in 1 2; do
    uplink_is_metered && { log "metered uplink is now the default route; not uploading"; return 3; }
    soft_k="$(python3 - "$BW_SOFT" <<'PY'
import sys
print(f"{int(float(sys.argv[1]) * 1000000 / 1024)}k")
PY
)"
    rcdir="$(mktemp -d "${STATE}/rc.XXXX")"; chmod 700 "$rcdir"
    podman unshare rclone --config "$RCLONE_CONFIG" copy "$f" "${TARGET}/${run}/" --stats-one-line --stats 0 \
      --bwlimit "$soft_k" --rc --rc-addr "unix://${rcdir}/rc.sock" --rc-no-auth \
      --transfers "$RCLONE_TRANSFERS" --checkers 2 --protondrive-replace-existing-draft </dev/null &
    rpid=$!
    set +e
    guard_json="$(python3 "$RATE_GUARD" --pid "$rpid" --rc-sock "${rcdir}/rc.sock" --iface "$BW_IFACE" --soft-mb "$BW_SOFT" --hard-mb "$BW_HARD" </dev/null)"; grc=$?
    wait "$rpid"; src=$?; set -e; rm -rf "$rcdir"
    log "upload $(basename "$f") attempt ${attempt}: rclone ${src}, rate guard ${grc}"
    (( src == 0 )) && return 0
    (( grc == 4 && attempt == 1 )) || return 1
  done
  return 1
}

stream_object() {  # name, producer...: straight to the remote (small objects only, when nothing can be staged)
  local name="$1"; shift
  uplink_is_metered && { log "metered uplink; ${name} not streamed"; return 3; }
  set +e
  "$@" | zstd -q -T1 -6 | encrypt | python3 "$TAP" "${META_DIR}/${name}.json" \
    | podman unshare rclone --config "$RCLONE_CONFIG" rcat "${TARGET}/${run}/${name}"
  local rc=("${PIPESTATUS[@]}"); set -e
  for r in "${rc[@]}"; do (( r == 0 || r == 1 )) || { log "stream of ${name} failed (${rc[*]})"; return 1; }; done
  return 0
}

stage_object() {   # name, producer...: stage (bounded), re-read, upload, verify remote, delete
  local name="$1"; shift
  local out="${RUN_STAGE}/${name}" room meta check rc
  room=$(( $(python3 "$STAGE_GUARD" free "$RUN_STAGE") - MIN_FREE ))
  (( room > 0 )) || { log "no room above the reserve for ${name}"; return 1; }
  set +e
  "$@" | zstd -q -T1 -6 | encrypt | python3 "$TAP" "${META_DIR}/${name}.json" | python3 "$STAGE_GUARD" limit "$out" "$room"
  rc=("${PIPESTATUS[@]}"); set -e
  # producer exit 1 is tolerated for tar ("file changed as we read it"); everything else must be 0
  (( rc[0] == 0 || rc[0] == 1 )) && (( rc[1] == 0 && rc[2] == 0 && rc[3] == 0 && rc[4] == 0 )) \
    || { rm -f "$out"; log "staging ${name} failed (${rc[*]})"; return 1; }
  meta="$(cat "${META_DIR}/${name}.json")"
  check="$(python3 "$TAP" --file "$out")"
  python3 "$TAP" --same "$meta" "$check" \
    || { rm -f "$out"; log "re-read of staged ${name} does not match its write-time hash"; return 1; }
  upload_file "$out" || { local u=$?; rm -f "$out"; return "$u"; }
  remote_check "$name" "$meta" || { rm -f "$out"; log "remote check of ${name} failed"; return 1; }
  rm -f "$out"
  return 0
}

do_object() {      # name, estimated bytes, producer...
  local name="$1" estb="$2"; shift 2
  local rc=0 mode="$STAGE_MODE"
  if [[ "$STAGE_MODE" == stream ]]; then
    if (( estb > STREAM_MAX )); then
      log "SKIPPED ${name}: nothing can stage it and it is too large to stream (est $(( estb / 1048576 )) MiB > $(( STREAM_MAX / 1048576 )) MiB)"
      ledger note "{\"mode\": \"direct\", \"run\": \"${run}\", \"skipped\": \"${name}\", \"reason\": \"no stage; too large to stream\"}"
      PARTIAL=1; return 0
    fi
    stream_object "$name" "$@" || rc=$?
    if (( rc == 0 )); then remote_check "$name" "$(cat "${META_DIR}/${name}.json")" || rc=1; fi
  else
    stage_object "$name" "$@" || rc=$?
  fi
  if (( rc != 0 )); then
    log "object ${name} not backed up (rc ${rc})"
    ledger note "{\"mode\": \"direct\", \"run\": \"${run}\", \"failed\": \"${name}\", \"rc\": ${rc}}"
    PARTIAL=1; (( rc == 3 )) && return 3; return 0
  fi
  local meta; meta="$(cat "${META_DIR}/${name}.json")"
  ledger direct-object "{\"run\": \"${run}\", \"name\": \"${name}\", \"target\": \"${TARGET}\", \"staged\": \"${mode}\", \"meta\": ${meta}}"
  add_object "$name" "$meta" "$mode"
  log "object ${name} uploaded and verified ($(python3 "$TAP" --get "$meta" bytes) bytes)"
}

# ---- producers -------------------------------------------------------------------------------------------
pg_dump_out() {    # container, extra args
  podman exec -i "$1" sh -c "PGPASSWORD=\"\$POSTGRES_PASSWORD\" pg_dump -U \"\$POSTGRES_USER\" -d \"\$POSTGRES_DB\" -Fc -Z 0 ${2:-}" </dev/null
}
dump_dispatch() { pg_dump_out "$DISPATCH_PG" "$(printf -- '--exclude-table-data=%s ' "${LADD_TABLES[@]}")"; }
dump_nextcloud() { pg_dump_out "$NEXTCLOUD_PG"; }
STATE_PATHS=(/etc/corporatetraveldc /var/lib/corporatetraveldc /var/lib/vnstat /var/lib/ntfy /var/lib/openwebui
             /etc/ntfy /etc/pihole/pihole.toml /etc/pihole/hosts /etc/nftables.d /etc/nginx/conf.d /etc/fail2ban/jail.d /etc/unbound
             "${HOME}/.config/nextcloud" "${HOME}/.config/containers/systemd" "${HOME}/.config/systemd/user"
             "${HOME}/.config/rclone" "${HOME}/demos" "${HOME}/.local/state/corporatetraveldc" "${STATE}/ledger.jsonl")
tar_state() {
  local p have=()
  for p in "${STATE_PATHS[@]}"; do [[ -r "$p" ]] && have+=("$p"); done
  tar --create --file - --one-file-system --warning=no-file-changed \
      --exclude=/var/lib/corporatetraveldc/models --exclude=/var/lib/openwebui/cache \
      --exclude='__pycache__' --exclude='*.tmp' --exclude=/etc/corporatetraveldc/cf-honeypot.token "${have[@]}" 2>/dev/null
}
tar_volumes() {
  local v mp have=()
  for v in "${DIRECT_VOLUMES[@]}"; do
    mp="$(podman volume inspect "$v" --format '{{.Mountpoint}}' 2>/dev/null)" && [[ -n "$mp" ]] && have+=("$mp")
  done
  (( ${#have[@]} )) || return 0
  podman unshare tar --create --file - --warning=no-file-changed \
      --exclude='*/protonmail/bridge-v3/gluon' --exclude='*/protonmail/bridge-v3/logs' \
      --exclude='*/protonmail/bridge-v3/updates' --exclude='*/protonbridge-data/_data/.cache' "${have[@]}" 2>/dev/null
}

# ---- the run ---------------------------------------------------------------------------------------------
log "run ${run}: dispatch (LADD data excluded), nextcloud, state, volumes -> ${TARGET}/${run}/"
STOP=0
for spec in "dispatch.pgdump.zst.gpg:${EST_DISPATCH}:dump_dispatch" "nextcloud.pgdump.zst.gpg:${EST_NC}:dump_nextcloud" \
            "state.tar.zst.gpg:1073741824:tar_state" "volumes.tar.zst.gpg:1073741824:tar_volumes"; do
  IFS=: read -r name estb fn <<<"$spec"
  if (( STOP )); then ledger note "{\"mode\": \"direct\", \"run\": \"${run}\", \"failed\": \"${name}\", \"rc\": 3}"; PARTIAL=1; continue; fi
  do_object "$name" "$estb" "$fn" || STOP=1   # rc 3: the uplink turned metered -- no further uploads this run
done

# CUI "#" stamp: LADD stays on the box; record its row count and the import-ledger head
count_sql=$(printf "SELECT json_build_object(%s)" "$(printf "'%s', (SELECT count(*) FROM %s)," $(for t in "${LADD_TABLES[@]}"; do echo "$t $t"; done) | sed 's/,$//')")
ladd_rows=$(psql_in "$DISPATCH_PG" "${count_sql}" 2>/dev/null || true)
ledger cui-stamp "{\"stamp\": \"#\", \"mode\": \"direct\", \"run\": \"${run}\", \"rows\": ${ladd_rows:-null}, \"off_box\": false, \"local_dump\": null}"

# manifest (sizes and hashes only) uploaded beside the objects
if [[ "$OBJECTS" != "[]" ]] && ! uplink_is_metered; then
  python3 - "$run" "$OBJECTS" "$(python3 "$LEDGER_PY" head)" <<'PY' | podman unshare rclone --config "$RCLONE_CONFIG" rcat "${TARGET}/${run}/MANIFEST.json" || PARTIAL=1
import json, sys
print(json.dumps({"run": sys.argv[1], "objects": json.loads(sys.argv[2]), "ledger_head_before_manifest": sys.argv[3],
                  "encryption": "gpg public-key (operator key off the box)", "ladd_off_box": False}, indent=1))
PY
fi
ledger direct-backup "{\"run\": \"${run}\", \"target\": \"${TARGET}\", \"stage\": \"${STAGE_MODE}\", \"ok\": $( (( PARTIAL )) && echo false || echo true ), \"objects\": ${OBJECTS}}"

# retention: only run folders this script creates, only under BACKUP_TARGET_DIRECT
if (( ! PARTIAL )); then
  mapfile -t drop < <(podman unshare rclone --config "$RCLONE_CONFIG" lsf --dirs-only "$TARGET" </dev/null 2>/dev/null \
    | python3 "${HERE}/direct_retention.py" --daily "$KEEP_D" --weekly "$KEEP_W" --monthly "$KEEP_M")
  for r in "${drop[@]}"; do
    [[ "$r" =~ ^[0-9]{8}T[0-9]{6}Z$ && "$r" != "$run" ]] || continue
    podman unshare rclone --config "$RCLONE_CONFIG" purge "${TARGET}/${r}" </dev/null && log "retention: removed ${r}"
  done
  ledger direct-retention "{\"run\": \"${run}\", \"removed\": $(printf '%s\n' "${drop[@]:-}" | python3 "${HERE}/direct_retention.py" --as-json)}"
fi
python3 "$LEDGER_PY" verify
(( PARTIAL )) && die "run ${run} PARTIAL: one or more objects not backed up (see the lines above); the unit fails so OnFailure alerts"
log "run ${run} complete: every object uploaded and verified; nothing left staged"
